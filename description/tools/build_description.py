#!/usr/bin/env python3
"""Turn the raw Fusion exports into the robot description.

    python description/tools/build_description.py

Reads
    description/arm.json                 joints, links, tcp - the source of truth
    description/cad-raw/<part>.stl       bodies exported by tools/fusion_export (Fusion),
                                         each in its OWN component frame
    description/cad-raw/transforms.json  where each body sits in the assembly

Writes
    description/meshes/<link>.stl        every part of a link merged, in that
                                         link's frame (mm, binary STL)
    description/robotic_arm.urdf         for ROS 2, MuJoCo, PyBullet, viewers (m)

Why the transforms: a body exported from an occurrence comes out in its
component's coordinates, not the assembly's. The forearm and wrist were moved
70 mm down when the upper arm shrank from 200 to 130 mm, so skipping this step
puts them in mid-air.
"""
from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "cad-raw"
MESHES = ROOT / "meshes"

# PLA printed at the usual 3 walls / 20-40 % infill weighs roughly this much
# per solid cm^3 of the CAD body. Only used when arm.json gives no mass.
EFFECTIVE_DENSITY_G_CM3 = 0.65


def read_stl(path: Path) -> np.ndarray:
    """Binary STL -> (n, 3, 3) float64 triangles."""
    data = path.read_bytes()
    n = struct.unpack("<I", data[80:84])[0]
    rec = np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")])
    tri = np.frombuffer(data, dtype=rec, count=n, offset=84)
    return tri["v"].astype(np.float64)


def write_stl(path: Path, tris: np.ndarray) -> None:
    a, b, c = tris[:, 0], tris[:, 1], tris[:, 2]
    nrm = np.cross(b - a, c - a)
    ln = np.linalg.norm(nrm, axis=1, keepdims=True)
    nrm = np.divide(nrm, ln, out=np.zeros_like(nrm), where=ln > 0)
    rec = np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")])
    out = np.zeros(len(tris), dtype=rec)
    out["n"], out["v"] = nrm, tris
    header = b"robotic_arm description mesh (mm, link frame)".ljust(80, b" ")
    path.write_bytes(header + struct.pack("<I", len(tris)) + out.tobytes())


def mass_props(tris: np.ndarray):
    """Volume (mm^3), centroid (mm) and inertia about the centroid for a
    closed mesh of unit density, by signed tetrahedra."""
    a, b, c = tris[:, 0], tris[:, 1], tris[:, 2]
    v = np.einsum("ij,ij->i", a, np.cross(b, c)) / 6.0
    vol = v.sum()
    if abs(vol) < 1e-9:
        return 0.0, tris.reshape(-1, 3).mean(0), np.eye(3)
    com = ((a + b + c) / 4.0 * v[:, None]).sum(0) / vol
    # Covariance of each tetrahedron (origin, a, b, c) - standard formula.
    C = np.zeros((3, 3))
    for p, q, r, w in zip(a, b, c, v):
        s = p + q + r
        C += w / 20.0 * (np.outer(p, p) + np.outer(q, q) + np.outer(r, r) + np.outer(s, s))
    C -= vol * np.outer(com, com)
    inertia = np.trace(C) * np.eye(3) - C
    return abs(vol), com, inertia * np.sign(vol)


def main() -> int:
    spec = json.loads((ROOT / "arm.json").read_text())
    xforms = json.loads((RAW / "transforms.json").read_text())
    joints = {j["child"]: j for j in spec["joints"]}
    MESHES.mkdir(exist_ok=True)

    link_info = {}
    for link in spec["links"]:
        name = link["name"]
        origin = np.array(joints[name]["position"]) if name in joints else np.zeros(3)
        parts = []
        for part in link["meshes"]:
            tris = read_stl(RAW / f"{part}.stl")
            M = np.array(xforms[part]["matrix"], dtype=float).reshape(4, 4)
            pts = tris.reshape(-1, 3) @ M[:3, :3].T + M[:3, 3]
            parts.append((pts - origin).reshape(-1, 3, 3))
        merged = np.concatenate(parts)
        write_stl(MESHES / f"{name}.stl", merged)
        vol, com, I = mass_props(merged)
        mass = link.get("mass_kg") or vol * 1e-3 * EFFECTIVE_DENSITY_G_CM3 / 1000.0
        # scale unit-density inertia (mm^5) to kg*m^2 with the chosen mass
        I_kgm2 = I * (mass / vol) * 1e-6 if vol > 0 else np.eye(3) * 1e-5
        link_info[name] = dict(origin=origin, com=com, mass=mass, inertia=I_kgm2,
                               tris=len(merged))
        lo, hi = merged.reshape(-1, 3).min(0), merged.reshape(-1, 3).max(0)
        print(f"{name:12s} {len(merged):6d} tris  mass {mass:5.2f} kg  "
              f"bbox {np.round(lo, 1)} .. {np.round(hi, 1)} (link frame)")

    write_urdf(spec, link_info)
    return 0


def _v(x, k=1e-3):
    return " ".join(f"{v * k:.6g}" for v in x)


def write_urdf(spec: dict, info: dict) -> None:
    """URDF in metres. Visuals and collisions use the same mesh."""
    out = ['<?xml version="1.0"?>',
           f'<!-- generated by description/tools/build_description.py from arm.json - do not edit -->',
           f'<robot name="{spec["name"]}">',
           '  <material name="printed"><color rgba="0.12 0.12 0.13 1"/></material>']
    for link in spec["links"]:
        n = link["name"]
        li = info[n]
        I = li["inertia"]
        out += [
            f'  <link name="{n}">',
            f'    <inertial><origin xyz="{_v(li["com"])}" rpy="0 0 0"/><mass value="{li["mass"]:.4f}"/>',
            f'      <inertia ixx="{I[0,0]:.3e}" ixy="{I[0,1]:.3e}" ixz="{I[0,2]:.3e}" '
            f'iyy="{I[1,1]:.3e}" iyz="{I[1,2]:.3e}" izz="{I[2,2]:.3e}"/></inertial>',
            f'    <visual><geometry><mesh filename="meshes/{n}.stl" scale="0.001 0.001 0.001"/></geometry>'
            f'<material name="printed"/></visual>',
            f'    <collision><geometry><mesh filename="meshes/{n}.stl" scale="0.001 0.001 0.001"/></geometry></collision>',
            '  </link>']
    pos = {spec["links"][0]["name"]: [0.0, 0.0, 0.0]}
    for j in spec["joints"]:
        pos[j["child"]] = j["position"]
    for j in spec["joints"]:
        rel = np.array(j["position"]) - np.array(pos[j["parent"]])
        lo, hi = (np.radians(v) for v in j["limit"])
        effort = 8.0 if j["kind"] == "stepper" else 1.2
        out += [
            f'  <joint name="{j["name"]}" type="revolute">',
            f'    <parent link="{j["parent"]}"/><child link="{j["child"]}"/>',
            f'    <origin xyz="{_v(rel)}" rpy="0 0 0"/><axis xyz="{" ".join(str(a) for a in j["axis"])}"/>',
            f'    <limit lower="{lo:.4f}" upper="{hi:.4f}" effort="{effort}" velocity="1.0"/>',
            '  </joint>']
    tcp = spec["tcp"]
    rel = np.array(tcp["position"]) - np.array(pos[tcp["parent"]])
    out += ['  <link name="tcp"/>',
            '  <joint name="tcp_fixed" type="fixed">',
            f'    <parent link="{tcp["parent"]}"/><child link="tcp"/>',
            f'    <origin xyz="{_v(rel)}" rpy="0 0 0"/>',
            '  </joint>',
            '</robot>', '']
    (ROOT / "robotic_arm.urdf").write_text("\n".join(out))
    print("wrote", ROOT / "robotic_arm.urdf")


if __name__ == "__main__":
    sys.exit(main())
